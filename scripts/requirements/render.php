<?php

/*
 * Regenerates docs/requirements/*.md from docs/requirements/requirements.json (the single source of truth for
 * owners, sprints and notes). Run it after editing the JSON, and commit both:
 *
 *     docker compose exec app php scripts/requirements/render.php
 */

$root = dirname(__DIR__, 2);
$dir = "$root/docs/requirements";
$requirements = json_decode((string) file_get_contents("$dir/requirements.json"), true, flags: JSON_THROW_ON_ERROR);

$modules = [
    'security' => ['Security (sign-in and audit)', '@AleQuesada2012'],
    'assets' => ['Assets', '@DavidZamoraB'],
    'spaces' => ['Spaces', '@Dizabu'],
    'reservations' => ['Reservations', '@JoseHerrera21'],
    'reports' => ['Reports and dashboards', '@AleQuesada2012'],
    'users' => ['Users and roles', '@Rubiocai'],
];

$sprint = fn (array $r): string => match (true) {
    $r['delivered_in_bootstrap'] => 'Done (bootstrap)',
    default => 'Sprint '.$r['sprint'],
};
$status = function (array $r): string {
    $tags = [];
    if ($r['closes_with']) {
        $tags[] = "duplicate of {$r['closes_with']}";
    }
    if ($r['free_with'] ?? null) {
        $tags[] = "closes with {$r['free_with']}";
    }
    if ($r['cut_rank'] ?? null) {
        $tags[] = "cut #{$r['cut_rank']}";
    }

    return $tags === [] ? '' : ' ('.implode(', ', $tags).')';
};

$index = [
    '# Functional requirements',
    '',
    '<!-- Generated by scripts/requirements/render.php from requirements.json. Edit the JSON, then re-run the script. -->',
    '',
    'The 105 functional requirements (RF) of the approved analysis document (`Análisis-y-Diseño`, signed 2026-09-10). The',
    'requirement text is quoted in Spanish, as approved. Owners and sprints come from the backlog plan as rebalanced in',
    'planning round 3 (2026-09-29, see [../PLANNING.md](../PLANNING.md)). Each RF is one GitHub issue, where the work is tracked.',
    '',
    '- **Owner** implements it. **Reviewer** approves its PR: the module\'s buddy reviewer, or the module owner when the',
    '  owner works in someone else\'s module.',
    '- *closes with RF_xx*: no separate screen; it is delivered inside that RF\'s PR.',
    '- *cut #n*: dropped in that order if Sprint 3 runs late.',
    '',
    '| Module | File | Module owner |',
    '|---|---|---|',
];
foreach ($modules as $slug => [$title, $owner]) {
    $index[] = "| $title | [$slug.md]($slug.md) | $owner |";
}
$index = [...$index, '', '## All requirements', '', '| Code | Requirement | Module | Owner | Reviewer | Sprint |', '|---|---|---|---|---|---|'];
foreach ($requirements as $r) {
    $anchor = strtolower($r['code']);
    $index[] = "| [{$r['code']}]({$r['module']}.md#$anchor) | {$r['title']}{$status($r)} | {$r['module']} | @{$r['owner']} | @{$r['reviewer']} | {$sprint($r)} |";
}
file_put_contents("$dir/README.md", implode("\n", $index)."\n");

foreach ($modules as $slug => [$title, $owner]) {
    $out = [
        "# $title",
        '',
        '<!-- Generated by scripts/requirements/render.php from requirements.json. -->',
        '',
        "Requirements whose code lives in the $slug module (module owner: $owner). Full list: [README.md](README.md).",
        '',
    ];
    foreach (array_filter($requirements, fn (array $r) => $r['module'] === $slug) as $r) {
        $out[] = "## {$r['code']}";
        $out[] = '';
        $out[] = "**{$r['title']}** · owner @{$r['owner']} ({$r['owner_name']}) · reviewer @{$r['reviewer']} · {$sprint($r)}{$status($r)}";
        $out[] = '';
        $out[] = "> {$r['description']}";
        $out[] = '';
        $out[] = 'Acceptance criteria:';
        $out[] = '';
        foreach ($r['criteria'] as $criterion) {
            $out[] = "- $criterion";
        }
        if ($r['notes'] !== []) {
            $out[] = '';
            $out[] = 'Notes:';
            $out[] = '';
            foreach ($r['notes'] as $note) {
                $out[] = "- $note";
            }
        }
        if ($r['diagram']) {
            $out[] = '';
            $out[] = "Diagram: [Lucid]({$r['diagram']})";
        }
        $out[] = '';
    }
    file_put_contents("$dir/$slug.md", implode("\n", $out));
}

echo 'Rendered '.count($requirements)." requirements into docs/requirements/.\n";
