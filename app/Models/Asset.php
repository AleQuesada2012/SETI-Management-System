<?php

namespace App\Models;

use App\Enums\AssetStatus;
use App\Enums\MaintenanceKind;
use App\Enums\MaintenanceStatus;
use App\Support\Audit\Auditable;
use Database\Factories\AssetFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Casts\Attribute;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;
use LogicException;

/**
 * A physical item in SETI's custody, tracked individually (CONTEXT.md "Asset").
 *
 * - `code` (A-0014) is generated by PostgreSQL; `asset_tag` is the optional TEC placa (Q5).
 * - `current_space_id` is written ONLY by inserting an AssetMovement (ADR-0003). Setting it here throws.
 * - `status` (lifecycle) changes only as a side effect of events and maintenance (Agent-DB.md §8.4),
 *   so it is not mass-assignable; Actions call transitionTo(), which refuses a change AssetStatus does not allow.
 * - "Eliminar" (RF_02) is a soft delete; "dar de baja" (RF_29) is an AssetEvent. Never the same thing.
 *
 * @property int $id
 * @property string $code
 * @property string|null $asset_tag
 * @property string|null $serial_number
 * @property string|null $name
 * @property int $asset_type_id
 * @property int|null $brand_id
 * @property string|null $model
 * @property int $condition_id
 * @property string|null $condition_note
 * @property AssetStatus $status
 * @property int|null $current_space_id
 * @property string|null $location_detail
 * @property int|null $responsible_user_id
 * @property int|null $supplier_id
 * @property Carbon|null $acquired_on
 * @property Carbon|null $warranty_starts_on
 * @property Carbon|null $warranty_ends_on
 * @property string|null $observations
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
#[Fillable([
    'asset_tag', 'serial_number', 'name', 'asset_type_id', 'brand_id', 'model', 'condition_id', 'condition_note',
    'location_detail', 'responsible_user_id', 'supplier_id', 'acquired_on', 'warranty_starts_on', 'warranty_ends_on',
    'observations',
])]
class Asset extends Model
{
    /** @use HasFactory<AssetFactory> */
    use Auditable, HasFactory, SoftDeletes;

    protected $hidden = ['search_text'];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'status' => AssetStatus::class,
            'acquired_on' => 'date',
            'warranty_starts_on' => 'date',
            'warranty_ends_on' => 'date',
        ];
    }

    /** The location pointer is read-only for the application (ADR-0003). */
    protected function currentSpaceId(): Attribute
    {
        return Attribute::make(set: function (): never {
            throw new LogicException('assets.current_space_id changes only by creating an AssetMovement (entry, transfer or exit). See ADR-0003.');
        });
    }

    /** The system code; PostgreSQL generates it, this fallback mirrors the formula before a refresh. */
    protected function code(): Attribute
    {
        return Attribute::make(get: fn (?string $value): string => $value
            ?? 'A-'.str_pad((string) $this->getKey(), 4, '0', STR_PAD_LEFT));
    }

    /**
     * @return BelongsTo<AssetType, $this>
     */
    public function assetType(): BelongsTo
    {
        return $this->belongsTo(AssetType::class)->withTrashed();
    }

    /**
     * @return BelongsTo<Brand, $this>
     */
    public function brand(): BelongsTo
    {
        return $this->belongsTo(Brand::class)->withTrashed();
    }

    /**
     * @return BelongsTo<AssetCondition, $this>
     */
    public function condition(): BelongsTo
    {
        return $this->belongsTo(AssetCondition::class, 'condition_id')->withTrashed();
    }

    /**
     * @return BelongsTo<Space, $this>
     */
    public function currentSpace(): BelongsTo
    {
        return $this->belongsTo(Space::class, 'current_space_id')->withTrashed();
    }

    /**
     * The custodian (RF_23).
     *
     * @return BelongsTo<User, $this>
     */
    public function responsibleUser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'responsible_user_id');
    }

    /**
     * @return BelongsTo<Supplier, $this>
     */
    public function supplier(): BelongsTo
    {
        return $this->belongsTo(Supplier::class)->withTrashed();
    }

    /**
     * @return HasMany<AssetComponent, $this>
     */
    public function components(): HasMany
    {
        return $this->hasMany(AssetComponent::class);
    }

    /**
     * @return BelongsToMany<File, $this>
     */
    public function files(): BelongsToMany
    {
        return $this->belongsToMany(File::class, 'asset_files')
            ->withPivot(['kind', 'sort_order', 'created_at'])
            ->orderByPivot('sort_order');
    }

    /**
     * @return HasMany<AssetMovement, $this>
     */
    public function movements(): HasMany
    {
        return $this->hasMany(AssetMovement::class)->orderBy('moved_at');
    }

    /**
     * @return HasMany<AssetEvent, $this>
     */
    public function events(): HasMany
    {
        return $this->hasMany(AssetEvent::class)->orderBy('occurred_on');
    }

    /**
     * @return HasMany<MaintenanceRecord, $this>
     */
    public function maintenanceRecords(): HasMany
    {
        return $this->hasMany(MaintenanceRecord::class);
    }

    /** Label shown in lists: the optional name, or type + brand + model (Q6). */
    public function displayName(): string
    {
        if ($this->name !== null && $this->name !== '') {
            return $this->name;
        }

        return trim(implode(' ', array_filter([
            $this->assetType?->name,
            $this->brand?->name,
            $this->model,
        ])));
    }

    /**
     * Change the lifecycle status along an edge of AssetStatus::transitions(), inside the caller's transaction and on
     * the locked row. An Action validates first and tells the user why; reaching this with a forbidden change is a bug.
     *
     * @throws LogicException when the current status does not allow the new one
     */
    public function transitionTo(AssetStatus $status): void
    {
        if (! $this->status->canTransitionTo($status)) {
            throw new LogicException("An asset cannot go from {$this->status->value} to {$status->value} (Agent-DB.md §8.4).");
        }

        $this->forceFill(['status' => $status])->save();
    }

    /** A repair (corrective maintenance) of this asset is in progress; at most one is (RF_11). */
    public function hasRepairInProgress(): bool
    {
        return $this->maintenanceRecords()
            ->where('kind', MaintenanceKind::Corrective)
            ->where('status', MaintenanceStatus::InProgress)
            ->exists();
    }

    /**
     * A decommission is terminal (RF_29, Agent-DB.md §8.4): the asset keeps its history and may still exit its space or
     * be deleted (RF_02), but its data, components and files no longer change (decision of 2026-10-16).
     */
    public function isReadOnly(): bool
    {
        return $this->status === AssetStatus::Decommissioned;
    }

    /** The space whose managers answer for this asset: where it is, or where it last was (Agent-DB.md §8.1). */
    public function responsibleSpaceId(): ?int
    {
        if ($this->current_space_id !== null) {
            return $this->current_space_id;
        }

        $lastExit = $this->movements()->reorder('moved_at', 'desc')->whereNotNull('from_space_id')->first();

        return $lastExit?->from_space_id;
    }

    public function auditLabel(): string
    {
        $this->loadMissing(['assetType', 'brand', 'currentSpace']);

        return implode(' · ', array_filter([$this->code, $this->displayName(), $this->currentSpace?->code]));
    }
}
