-- =============================================================================
-- 4. Files: bytes live on a Laravel Storage disk; the DB keeps metadata (Q17/Q18)
-- =============================================================================
CREATE TABLE files (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disk           varchar(30)  NOT NULL,     -- Laravel filesystem disk: 'local', 's3', ...
    path           varchar(500) NOT NULL,
    original_name  varchar(255) NOT NULL,
    mime_type      varchar(100) NOT NULL,
    size_bytes     bigint       NOT NULL,
    sha256         char(64)     NOT NULL,     -- integrity / duplicate detection
    width          integer,                   -- images only
    height         integer,
    thumbnail_path varchar(500),              -- ~400 px WebP for phones, generated on upload
    uploaded_by    bigint REFERENCES users (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT files_disk_path_unique UNIQUE (disk, path),
    CONSTRAINT files_mime_type_check CHECK (mime_type IN (
        'image/jpeg', 'image/png', 'image/webp', 'image/gif',
        'application/pdf',
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')),  -- xlsx: exported reports only
    CONSTRAINT files_size_check CHECK (
        size_bytes > 0
        AND size_bytes <= CASE WHEN mime_type LIKE 'image/%' THEN 10485760   -- 10 MB
                               ELSE 20971520 END),                          -- 20 MB
    CONSTRAINT files_sha256_check CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT files_dimensions_check CHECK ((width IS NULL AND height IS NULL) OR (width > 0 AND height > 0))
);
CREATE INDEX files_uploaded_by_index ON files (uploaded_by);
CREATE INDEX files_sha256_index ON files (sha256);
COMMENT ON TABLE files IS 'Metadata of stored files. Each file belongs to exactly one owner through one link table (asset_files, space_photos, asset_event_evidence, report_generations).';

-- =============================================================================
-- 5. Spaces (RF_32–RF_59)
-- =============================================================================
CREATE TABLE spaces (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(30)  NOT NULL,    -- short identifier searched in RF_42 (e.g. LAB-110)
    name            varchar(120) NOT NULL,    -- unique (RF_32 diagram)
    space_type_id   bigint NOT NULL REFERENCES space_types (id),
    space_status_id bigint NOT NULL REFERENCES space_statuses (id),
    building_id     bigint NOT NULL REFERENCES buildings (id),
    floor           varchar(20),
    location_detail varchar(200),
    capacity        integer NOT NULL,         -- people (RF_36)
    notes           text,
    search_text     text GENERATED ALWAYS AS (
                        lower(public.immutable_unaccent(
                            code || ' ' || name || ' ' || coalesce(floor, '') || ' ' || coalesce(location_detail, '')))
                    ) STORED,
    created_at      timestamptz NOT NULL DEFAULT now(),   -- RF_38 sort
    updated_at      timestamptz NOT NULL DEFAULT now(),   -- RF_37 sort
    deleted_at      timestamptz,
    CONSTRAINT spaces_code_check CHECK (btrim(code) <> ''),
    CONSTRAINT spaces_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT spaces_capacity_check CHECK (capacity > 0)
);
CREATE UNIQUE INDEX spaces_code_unique ON spaces (lower(code)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX spaces_name_unique ON spaces (lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX spaces_space_type_id_index ON spaces (space_type_id);
CREATE INDEX spaces_space_status_id_index ON spaces (space_status_id);
CREATE INDEX spaces_building_id_index ON spaces (building_id);
CREATE INDEX spaces_search_text_trgm_index ON spaces USING gin (search_text gin_trgm_ops);

CREATE TABLE space_managers (                 -- = "responsable" = RF_40 admin assignment (Q11, Q26)
    space_id    bigint NOT NULL REFERENCES spaces (id),
    user_id     bigint NOT NULL REFERENCES users (id),
    assigned_by bigint REFERENCES users (id),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT space_managers_pkey PRIMARY KEY (space_id, user_id)
);
CREATE INDEX space_managers_user_id_index ON space_managers (user_id);
CREATE INDEX space_managers_assigned_by_index ON space_managers (assigned_by);
COMMENT ON TABLE space_managers IS 'Administradores in charge of a space. Only holders of the Administrador role (checked in Laravel, Q26).';

CREATE TABLE space_photos (                   -- RF_41
    space_id   bigint NOT NULL REFERENCES spaces (id),
    file_id    bigint NOT NULL REFERENCES files (id) ON DELETE CASCADE,
    sort_order smallint NOT NULL DEFAULT 0,
    caption    varchar(200),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT space_photos_pkey PRIMARY KEY (space_id, file_id),
    CONSTRAINT space_photos_file_id_unique UNIQUE (file_id)
);

-- =============================================================================
-- 6. Assets (RF_01–RF_31)
-- =============================================================================
CREATE TABLE assets (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                varchar(20) GENERATED ALWAYS AS (
                            'A-' || lpad(id::text, greatest(4, length(id::text)), '0')
                        ) STORED,                             -- system code A-0014, never truncated (Q5)
    asset_tag           varchar(50),                          -- TEC "placa"; optional (Q5)
    serial_number       varchar(100),
    name                varchar(150),                         -- optional label; display name falls back to type + brand + model (Q6)
    asset_type_id       bigint NOT NULL REFERENCES asset_types (id),       -- category derived through the type (3NF)
    brand_id            bigint REFERENCES brands (id),
    model               varchar(120),
    condition_id        bigint NOT NULL REFERENCES asset_conditions (id),  -- physical condition (Q8)
    condition_note      text,                                 -- RF_05 "descripción" of the condition
    status              varchar(20) NOT NULL DEFAULT 'in_service',          -- lifecycle status (Q8)
    current_space_id    bigint REFERENCES spaces (id),        -- written ONLY by the asset_movements trigger (Q9)
    location_detail     varchar(200),                         -- RF_18: e.g. 'Rack 2', 'Escritorio 5'
    responsible_user_id bigint REFERENCES users (id),         -- custodian, RF_23 (nullable: RF_78 lists assets without one)
    supplier_id         bigint REFERENCES suppliers (id),     -- RF_15
    acquired_on         date,                                 -- RF_14
    warranty_starts_on  date,                                 -- RF_16/RF_17/RF_75
    warranty_ends_on    date,
    observations        text,                                 -- RF_19
    search_text         text GENERATED ALWAYS AS (
                            lower(public.immutable_unaccent(
                                'A-' || lpad(id::text, greatest(4, length(id::text)), '0') || ' '
                                || coalesce(asset_tag, '') || ' ' || coalesce(serial_number, '') || ' '
                                || coalesce(name, '') || ' ' || coalesce(model, '')))
                        ) STORED,                             -- RF_07 (brand/type names are matched through joins)
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz,                          -- RF_02 "eliminar" = soft delete; NOT a decommission (Q3)
    CONSTRAINT assets_status_check CHECK (status IN ('in_service', 'in_maintenance', 'lost', 'decommissioned')),
    CONSTRAINT assets_warranty_pair_check CHECK ((warranty_starts_on IS NULL) = (warranty_ends_on IS NULL)),
    CONSTRAINT assets_warranty_range_check CHECK (warranty_ends_on >= warranty_starts_on)
);
CREATE UNIQUE INDEX assets_code_unique ON assets (code);
CREATE UNIQUE INDEX assets_asset_tag_unique ON assets (lower(asset_tag)) WHERE deleted_at IS NULL;
CREATE INDEX assets_asset_type_id_index ON assets (asset_type_id);
CREATE INDEX assets_brand_id_index ON assets (brand_id);
CREATE INDEX assets_condition_id_index ON assets (condition_id);
CREATE INDEX assets_status_index ON assets (status);
CREATE INDEX assets_current_space_id_index ON assets (current_space_id);
CREATE INDEX assets_responsible_user_id_index ON assets (responsible_user_id);
CREATE INDEX assets_supplier_id_index ON assets (supplier_id);
CREATE INDEX assets_acquired_on_index ON assets (acquired_on);
CREATE INDEX assets_search_text_trgm_index ON assets USING gin (search_text gin_trgm_ops);
COMMENT ON COLUMN assets.current_space_id IS 'Cached current location. Maintained exclusively by the asset_movements trigger; direct writes are rejected (ADR-0003).';
COMMENT ON COLUMN assets.status IS 'Lifecycle: in_service | in_maintenance | lost | decommissioned. Physical condition is condition_id (ADR-0004).';

CREATE TABLE asset_components (               -- RF_12, RF_31, RF_77: internal parts, not tracked on their own
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id      bigint NOT NULL REFERENCES assets (id),
    name          varchar(120) NOT NULL,      -- e.g. 'Memoria RAM'
    specs         text,                       -- e.g. '16 GB DDR4 3200'
    serial_number varchar(100),
    quantity      integer NOT NULL DEFAULT 1,
    notes         text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT asset_components_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT asset_components_quantity_check CHECK (quantity > 0)
);
CREATE INDEX asset_components_asset_id_index ON asset_components (asset_id);

CREATE TABLE asset_files (                    -- RF_20 documents, RF_21 photos
    asset_id   bigint NOT NULL REFERENCES assets (id),
    file_id    bigint NOT NULL REFERENCES files (id) ON DELETE CASCADE,
    kind       varchar(10) NOT NULL,
    sort_order smallint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT asset_files_pkey PRIMARY KEY (asset_id, file_id),
    CONSTRAINT asset_files_file_id_unique UNIQUE (file_id),
    CONSTRAINT asset_files_kind_check CHECK (kind IN ('photo', 'document'))
);

-- =============================================================================
-- 7. Asset history: events, movements, maintenance (Q9, Q10, Q24, Q25)
-- =============================================================================
CREATE TABLE asset_events (                   -- damage (RF_13), loss (RF_28), recovery, decommission (RF_22/RF_29)
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id      bigint NOT NULL REFERENCES assets (id),
    kind          varchar(15) NOT NULL,
    occurred_on   date NOT NULL,
    description   text NOT NULL,              -- damage description / loss description / decommission reason
