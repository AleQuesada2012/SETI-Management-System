CREATE TABLE space_types (                    -- Laboratorio, Sala, Oficina
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(80) NOT NULL,
    is_reservable boolean NOT NULL DEFAULT false,   -- spaces of this type can be booked (RF_46 "habilitado para reservar")
    description   text,
    created_at    timestamptz NOT NULL DEFAULT now(),
