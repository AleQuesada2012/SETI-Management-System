    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT asset_events_kind_check CHECK (kind IN ('damage', 'loss', 'recovery', 'decommission')),
    CONSTRAINT asset_events_description_check CHECK (btrim(description) <> ''),
    CONSTRAINT asset_events_id_asset_id_unique UNIQUE (id, asset_id)   -- target of the composite FK below
);
