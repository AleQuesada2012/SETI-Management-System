\set ON_ERROR_STOP on
BEGIN;
SET LOCAL search_path = public;

-- =============================================================================
-- 0. Extensions and helper functions
-- =============================================================================
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;  -- EXCLUDE (space_id WITH =, period WITH &&)
CREATE EXTENSION IF NOT EXISTS pg_trgm    WITH SCHEMA public;  -- partial-match search (RF_07, RF_42, RF_95)
CREATE EXTENSION IF NOT EXISTS unaccent   WITH SCHEMA public;  -- accent-insensitive search ("salon" finds "Salón")

-- unaccent() is only STABLE; generated columns and index expressions need an
-- IMMUTABLE function. Pinning the dictionary by schema-qualified name makes this
-- wrapper deterministic (the standard, well-known workaround).
CREATE OR REPLACE FUNCTION public.immutable_unaccent(text)
    RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    RETURN public.unaccent('public.unaccent'::regdictionary, $1);

-- =============================================================================
-- 1. Identity & access (framework-owned tables, shown with our additions)
--    Laravel: users, password_reset_tokens, sessions · Sanctum: personal_access_tokens
--    Spatie laravel-permission: permissions, roles, model_has_*, role_has_permissions
-- =============================================================================
CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(150) NOT NULL,                  -- display name; the docs' "nombre de usuario" (Q32)
    email             varchar(255) NOT NULL,                  -- the login identifier (Q32), stored lowercase
    email_verified_at timestamptz,                            -- set when the invitation is accepted (Q21)
    password          varchar(255),                           -- Laravel Hash (bcrypt); NULL until the invite is accepted (Q21)
    remember_token    varchar(100),
    last_login_at     timestamptz,
    deactivated_at    timestamptz,                            -- RF_88/RF_98: users are deactivated, never deleted (Q3)
    deactivated_by    bigint REFERENCES users (id),
    search_text       text GENERATED ALWAYS AS (
                          lower(public.immutable_unaccent(name || ' ' || email || ' ' || id::text))
                      ) STORED,                               -- RF_95: search by name or id
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_lowercase_check CHECK (email = lower(email)),
    CONSTRAINT users_email_format_check CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT users_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT users_deactivation_check CHECK (deactivated_by IS NULL OR deactivated_at IS NOT NULL)
);
CREATE INDEX users_deactivated_by_index ON users (deactivated_by);
CREATE INDEX users_search_text_trgm_index ON users USING gin (search_text gin_trgm_ops);
COMMENT ON TABLE users IS 'People with an account. Login = email + password. Never deleted: deactivated_at revokes access (RF_88).';
COMMENT ON COLUMN users.password IS 'Laravel Hash (bcrypt). NULL until the user accepts the emailed invitation (Q21).';

CREATE TABLE password_reset_tokens (          -- Laravel default; also carries invitation tokens (Q21)
    email      varchar(255) PRIMARY KEY,
    token      varchar(255) NOT NULL,         -- hashed by Laravel's password broker
    created_at timestamptz
);

CREATE TABLE sessions (                       -- Laravel default (session auth, Q19)
    id            varchar(255) PRIMARY KEY,
    user_id       bigint,
    ip_address    varchar(45),
    user_agent    text,
    payload       text NOT NULL,
    last_activity integer NOT NULL
);
CREATE INDEX sessions_user_id_index ON sessions (user_id);
CREATE INDEX sessions_last_activity_index ON sessions (last_activity);

CREATE TABLE personal_access_tokens (         -- Sanctum default; reserved for a future non-browser client (Q19)
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tokenable_type varchar(255) NOT NULL,
    tokenable_id   bigint NOT NULL,
    name           text NOT NULL,
    token          varchar(64) NOT NULL,      -- SHA-256 of the plain-text token
    abilities      text,
    last_used_at   timestamptz,
    expires_at     timestamptz,
    created_at     timestamptz,
    updated_at     timestamptz,
    CONSTRAINT personal_access_tokens_token_unique UNIQUE (token)
);
CREATE INDEX personal_access_tokens_tokenable_type_tokenable_id_index ON personal_access_tokens (tokenable_type, tokenable_id);
CREATE INDEX personal_access_tokens_expires_at_index ON personal_access_tokens (expires_at);

CREATE TABLE permissions (                    -- Spatie
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL,        -- e.g. 'assets.create' (fixed catalog, seed.sql)
    guard_name  varchar(255) NOT NULL,
    description text,                         -- added: shown by RF_100
    created_at  timestamptz,
    updated_at  timestamptz,
    CONSTRAINT permissions_name_guard_name_unique UNIQUE (name, guard_name)
);

CREATE TABLE roles (                          -- Spatie
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(255) NOT NULL,
    guard_name  varchar(255) NOT NULL,
    description text,                         -- added: RF_100 "descripción de sus funciones"
    is_system   boolean NOT NULL DEFAULT false, -- added: seeded roles cannot be renamed or deleted (Q27)
    created_at  timestamptz,
    updated_at  timestamptz,
    CONSTRAINT roles_name_guard_name_unique UNIQUE (name, guard_name)
);

CREATE TABLE model_has_permissions (          -- Spatie (direct user permissions; normally unused)
    permission_id bigint       NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    model_type    varchar(255) NOT NULL,
    model_id      bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,  -- added FK (Q20)
    CONSTRAINT model_has_permissions_pkey PRIMARY KEY (permission_id, model_id, model_type),
    CONSTRAINT model_has_permissions_model_type_check CHECK (model_type = 'user')  -- enforced morph map
);
CREATE INDEX model_has_permissions_model_id_model_type_index ON model_has_permissions (model_id, model_type);

CREATE TABLE model_has_roles (                -- Spatie: a user holds 1..n roles (Q20, Q27)
    role_id    bigint       NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    model_type varchar(255) NOT NULL,
    model_id   bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,     -- added FK (Q20)
    CONSTRAINT model_has_roles_pkey PRIMARY KEY (role_id, model_id, model_type),
    CONSTRAINT model_has_roles_model_type_check CHECK (model_type = 'user')        -- enforced morph map
);
CREATE INDEX model_has_roles_model_id_model_type_index ON model_has_roles (model_id, model_type);

CREATE TABLE role_has_permissions (           -- Spatie
    permission_id bigint NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    role_id       bigint NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT role_has_permissions_pkey PRIMARY KEY (permission_id, role_id)
);
CREATE INDEX role_has_permissions_role_id_index ON role_has_permissions (role_id);

-- =============================================================================
-- 2. Notifications (Laravel database channel, Q15/Q16/Q30)
-- =============================================================================
CREATE TABLE notifications (
    id              uuid PRIMARY KEY,
    type            varchar(255) NOT NULL,    -- short stable code via databaseType(), e.g. 'reservation.created'
    notifiable_type varchar(255) NOT NULL,
    notifiable_id   bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,       -- added FK: only users are notified
    data            jsonb NOT NULL,           -- snapshot payload (space, dates, actor) + ids for links
    read_at         timestamptz,
    created_at      timestamptz,
    updated_at      timestamptz,
    CONSTRAINT notifications_notifiable_type_check CHECK (notifiable_type = 'user'),
    CONSTRAINT notifications_data_check CHECK (jsonb_typeof(data) = 'object')
);
CREATE INDEX notifications_notifiable_type_notifiable_id_index ON notifications (notifiable_type, notifiable_id);
CREATE INDEX notifications_notifiable_id_created_at_index ON notifications (notifiable_id, created_at DESC);  -- inbox + unread badge
COMMENT ON TABLE notifications IS 'In-app inbox, one row per recipient (fan-out on write). JSON payload is a deliberate snapshot (ADR-0006). Not audited.';

-- =============================================================================
-- 3. Catalogs (user-editable lookups; soft-deletable, Q3/Q34)
-- =============================================================================
